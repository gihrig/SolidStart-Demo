---- Base app schema

-- Org
CREATE TABLE "org" (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  name varchar(128) NOT NULL UNIQUE,

  -- Timestamps
  cid bigint NOT NULL,
  ctime timestamp with time zone NOT NULL,
  mid bigint NOT NULL,
  mtime timestamp with time zone NOT NULL
);

-- User
CREATE TYPE user_typ AS ENUM ('Sys', 'User');

CREATE TABLE "user" (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,

  username varchar(128) NOT NULL UNIQUE,
  typ user_typ NOT NULL DEFAULT 'User',

  -- Profile
  --   Persisted avatar URL (#117). The merge moves the avatar off the front-end
  --   useAuth seam onto the User row, so the author snapshot on a Post, Caption,
  --   or Comment reads one back-end identity (ADR-0007, ADR-0011 addendum).
  avatar_url varchar(1024),

  -- Auth
  pwd varchar(256),
  pwd_salt uuid NOT NULL DEFAULT gen_random_uuid(),
  token_salt uuid NOT NULL DEFAULT gen_random_uuid(),

  -- Timestamps
  cid bigint NOT NULL,
  ctime timestamp with time zone NOT NULL,
  mid bigint NOT NULL,
  mtime timestamp with time zone NOT NULL  
);

-- Category
--   A static, back-end-owned taxonomy: no owner_id, no AI fields. The icon is
--   an opaque key the back-end never interprets (ADR-0011). The front-end maps
--   it to a sprite name with a fallback.
CREATE TABLE category (
  -- PK
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,

  -- Properties
  name varchar(256) NOT NULL,
  icon varchar(256) NOT NULL,

  -- Timestamps
  cid bigint NOT NULL,
  ctime timestamp with time zone NOT NULL,
  mid bigint NOT NULL,
  mtime timestamp with time zone NOT NULL
);

---- Jedi merged schema (#117)

-- Post
--   The core feed entity: a shared Flickr photo. Every Post is public — read is
--   unscoped, write is owner-only (ADR-0011, #106). It carries an owner, an
--   external photographer attribution, and, via post_category, at least one
--   Category. Derived like / comment counts come from post_like / post_comment.
CREATE TABLE post (
  -- PK
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,

  -- FKs
  owner_id BIGINT NOT NULL,

  -- Properties
  title varchar(256) NOT NULL,
  image_src varchar(1024) NOT NULL,
  image_alt varchar(256) NOT NULL,
  photographer varchar(256) NOT NULL,
  photographer_url varchar(1024) NOT NULL,
  source_url varchar(1024) NOT NULL,

  -- Timestamps
  cid bigint NOT NULL,
  ctime timestamp with time zone NOT NULL,
  mid bigint NOT NULL,
  mtime timestamp with time zone NOT NULL
);

ALTER TABLE post ADD CONSTRAINT fk_post_owner
  FOREIGN KEY (owner_id) REFERENCES "user"(id)
  ON DELETE CASCADE;

-- Post <-> Category join
--   Many-to-many, minimum one Category per Post (#107). Category resolution reads
--   this join with a portable batched IN query, never array_agg (#117).
CREATE TABLE post_category (
  -- PK
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,

  -- FKs
  post_id BIGINT NOT NULL,
  category_id BIGINT NOT NULL,

  -- Timestamps
  cid bigint NOT NULL,
  ctime timestamp with time zone NOT NULL,
  mid bigint NOT NULL,
  mtime timestamp with time zone NOT NULL
);

ALTER TABLE post_category ADD CONSTRAINT fk_post_category_post
  FOREIGN KEY (post_id) REFERENCES "post"(id)
  ON DELETE CASCADE;

-- RESTRICT, not CASCADE: a Category in use may not be deleted, because a Post
-- must keep at least one Category (#107). Cascading here would silently orphan a
-- Post whose only Category is removed. The post side (below) still cascades.
ALTER TABLE post_category ADD CONSTRAINT fk_post_category_category
  FOREIGN KEY (category_id) REFERENCES "category"(id)
  ON DELETE RESTRICT;

-- Every Post view assembly reads the links by post_id (#124).
CREATE INDEX idx_post_category_post_id ON post_category (post_id);

-- Post Likes
--   One User's endorsement of one Post (#106). The dev seed casts Likes that match
--   the fixture likeCount (#177). The like count is derived by COUNT over this
--   table, never stored on the Post.
CREATE TABLE post_like (
  -- PK
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,

  -- FKs
  post_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,

  -- At most one Like per (Post, User): a User's endorsement counts once even if
  -- they click twice (#106, #122). The one-like invariant lives at the DB, not in
  -- application code, so a double-insert race cannot create a second Like.
  CONSTRAINT uq_post_like_post_user UNIQUE (post_id, user_id),

  -- Timestamps
  cid bigint NOT NULL,
  ctime timestamp with time zone NOT NULL,
  mid bigint NOT NULL,
  mtime timestamp with time zone NOT NULL
);

ALTER TABLE post_like ADD CONSTRAINT fk_post_like_post
  FOREIGN KEY (post_id) REFERENCES "post"(id)
  ON DELETE CASCADE;

ALTER TABLE post_like ADD CONSTRAINT fk_post_like_user
  FOREIGN KEY (user_id) REFERENCES "user"(id)
  ON DELETE CASCADE;

-- Post Comments
--   A User's remark in a Post's thread (#108, #124). Empty at seed, so a Post's
--   derived comment count resolves to 0 until a User comments. The comment count
--   is derived by COUNT over this table, never stored on the Post. Every Comment
--   is public: read is unscoped, write is owner-only.
CREATE TABLE post_comment (
  -- PK
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,

  -- FKs
  post_id BIGINT NOT NULL,
  owner_id BIGINT NOT NULL,

  -- Properties
  content varchar(2000) NOT NULL,

  -- Timestamps
  cid bigint NOT NULL,
  ctime timestamp with time zone NOT NULL,
  mid bigint NOT NULL,
  mtime timestamp with time zone NOT NULL
);

ALTER TABLE post_comment ADD CONSTRAINT fk_post_comment_post
  FOREIGN KEY (post_id) REFERENCES "post"(id)
  ON DELETE CASCADE;

ALTER TABLE post_comment ADD CONSTRAINT fk_post_comment_owner
  FOREIGN KEY (owner_id) REFERENCES "user"(id)
  ON DELETE CASCADE;

-- The thread read and the derived comment count filter by post_id (#124).
CREATE INDEX idx_post_comment_post_id ON post_comment (post_id);

-- Caption
--   An independently-liked line of text a User submits for a Post (#118). Many
--   Captions compete per Post, each ranked by its own Likes (Top Captions). Every
--   Caption is public: read is unscoped, write is owner-only. Derived like /
--   comment counts come from caption_like / caption_comment.
CREATE TABLE caption (
  -- PK
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,

  -- FKs
  post_id BIGINT NOT NULL,
  owner_id BIGINT NOT NULL,

  -- Properties
  text varchar(36) NOT NULL,

  -- Timestamps
  cid bigint NOT NULL,
  ctime timestamp with time zone NOT NULL,
  mid bigint NOT NULL,
  mtime timestamp with time zone NOT NULL
);

ALTER TABLE caption ADD CONSTRAINT fk_caption_post
  FOREIGN KEY (post_id) REFERENCES "post"(id)
  ON DELETE CASCADE;

ALTER TABLE caption ADD CONSTRAINT fk_caption_owner
  FOREIGN KEY (owner_id) REFERENCES "user"(id)
  ON DELETE CASCADE;

-- Top Captions filters by post_id (#118 review).
CREATE INDEX idx_caption_post_id ON caption (post_id);

-- Caption Likes
--   One User's endorsement of one Caption (#106). Same shape as post_like. The dev
--   seed casts Likes that match the fixture likeCount (#177). The like count is
--   derived by COUNT over this table, never stored.
CREATE TABLE caption_like (
  -- PK
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,

  -- FKs
  caption_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,

  -- At most one Like per (Caption, User), enforced at the DB (see post_like).
  CONSTRAINT uq_caption_like_caption_user UNIQUE (caption_id, user_id),

  -- Timestamps
  cid bigint NOT NULL,
  ctime timestamp with time zone NOT NULL,
  mid bigint NOT NULL,
  mtime timestamp with time zone NOT NULL
);

ALTER TABLE caption_like ADD CONSTRAINT fk_caption_like_caption
  FOREIGN KEY (caption_id) REFERENCES "caption"(id)
  ON DELETE CASCADE;

ALTER TABLE caption_like ADD CONSTRAINT fk_caption_like_user
  FOREIGN KEY (user_id) REFERENCES "user"(id)
  ON DELETE CASCADE;

-- Caption Comments
--   A User's remark in a Caption's thread (#108). Empty at seed, so a Caption's
--   derived comment count resolves to 0 until Comments land (#127). The comment
--   count is derived by COUNT over this table, never stored on the Caption.
CREATE TABLE caption_comment (
  -- PK
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,

  -- FKs
  caption_id BIGINT NOT NULL,
  owner_id BIGINT NOT NULL,

  -- Properties
  content varchar(2000) NOT NULL,

  -- Timestamps
  cid bigint NOT NULL,
  ctime timestamp with time zone NOT NULL,
  mid bigint NOT NULL,
  mtime timestamp with time zone NOT NULL
);

ALTER TABLE caption_comment ADD CONSTRAINT fk_caption_comment_caption
  FOREIGN KEY (caption_id) REFERENCES "caption"(id)
  ON DELETE CASCADE;

ALTER TABLE caption_comment ADD CONSTRAINT fk_caption_comment_owner
  FOREIGN KEY (owner_id) REFERENCES "user"(id)
  ON DELETE CASCADE;

-- The derived comment count groups by caption_id (#118 review). The caption_like
-- key needs no index: its UNIQUE (caption_id, user_id) constraint leads with it.
CREATE INDEX idx_caption_comment_caption_id ON caption_comment (caption_id);

-- Hero
--   The home page banner content (#119): a back-end-owned singleton an Admin
--   user edits. No owner_id and no cta_href (the CTA runs fixed front-end code,
--   ADR-0011 addendum). The CHECK keeps it a singleton: the one row is id 1.
--   The varchar caps back up the write-path hygiene caps (ADR-0019).
CREATE TABLE hero (
  -- PK
  id BIGINT PRIMARY KEY CHECK (id = 1),

  -- Properties
  title varchar(40) NOT NULL,
  subtitle varchar(100) NOT NULL,
  cta_text varchar(20) NOT NULL,
  background_image varchar(1024) NOT NULL,

  -- Timestamps
  cid bigint NOT NULL,
  ctime timestamp with time zone NOT NULL,
  mid bigint NOT NULL,
  mtime timestamp with time zone NOT NULL
);
